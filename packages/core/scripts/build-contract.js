// Compiles contracts/HoneypotSimulator.sol and writes src/simulator-artifact.js.
// The artifact is committed, so users never need a Solidity compiler.
// Run with: npm run build:contract
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { compile, SOLC_VERSION } from './solc.js';

const sourcePath = fileURLToPath(new URL('../../../contracts/HoneypotSimulator.sol', import.meta.url));
const outPath = fileURLToPath(new URL('../src/simulator-artifact.js', import.meta.url));

export function buildArtifact() {
  const source = readFileSync(sourcePath, 'utf8');
  const out = compile({ 'HoneypotSimulator.sol': source })['HoneypotSimulator.sol'].HoneypotSimulator;
  return {
    compiler: SOLC_VERSION,
    sourceHash: '0x' + createHash('sha256').update(source).digest('hex'),
    abi: out.abi,
    deployedBytecode: '0x' + out.evm.deployedBytecode.object,
  };
}

export function renderArtifact(artifact) {
  return (
    '// AUTO-GENERATED by scripts/build-contract.js from contracts/HoneypotSimulator.sol. Do not edit.\n' +
    `export const simulatorArtifact = ${JSON.stringify(artifact, null, 2)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const artifact = buildArtifact();
  writeFileSync(outPath, renderArtifact(artifact));
  console.log(`HoneypotSimulator compiled with solc ${artifact.compiler}: ${(artifact.deployedBytecode.length - 2) / 2} bytes`);
}
